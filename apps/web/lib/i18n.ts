export type CopyKey = keyof typeof en;

export function useI18n() {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const sync = () => {
      const next = localStorage.getItem("ww_lang") === "te" ? "te" : "en";
      setLangState(next);
      document.documentElement.lang = next;
    };
    sync();
    window.addEventListener("ww-lang", sync);
    return () => window.removeEventListener("ww-lang", sync);
  }, []);

  function setLang(next: Lang) {
    localStorage.setItem("ww_lang", next);
    window.dispatchEvent(new Event("ww-lang"));
  }

  function t(key: CopyKey) {
    return (lang === "te" ? te : en)[key];
  }

  return { lang, setLang, t };
}
